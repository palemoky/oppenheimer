// Package fault 是代码缺陷类故障的开关（阶段 4，设计 docs/design/4a-chaos-prep.md 的 3.3、ADR-0041）。
//
// goroutine 泄漏、内存泄漏、死锁这类故障从外面造不出来，只能在服务里预埋一段有缺陷的实现，运行时用开关切过去。
// 这个包只管开关，有缺陷的实现放在各自的业务包里。
//
// # 两种构建
//
// 不带标签的构建（平时的、CI 的、上线的）：Compiled 是 false，Register 什么都不挂，没有 Switch 这个函数。
// 业务包里带 //go:build faults 的文件根本不参加编译，二进制里没有任何有缺陷的代码（scripts/check-faults.sh 核对）。
//
// 带 -tags faults 的构建：Switch 登记开关，Register 在服务内部的管理端口上挂出
//
//	GET /fault                              列出全部开关
//	PUT /fault/{name}?mode=on&ttl=30m       打开，ttl 到了自己关（默认 30 分钟，最长 6 小时）
//	PUT /fault/{name}?mode=off              关掉
//
// 接口没有鉴权，和 /degrade 一样只能挂在不对外的端口上。
//
// # 一个故障点怎么写
//
// 在业务包里找一个“接缝”函数，拆成三个文件：
//
//	fetch.go            调用 fetchPrice(ctx, sku)，不带标签
//	fetch_default.go    //go:build !faults    fetchPrice 就是正确的实现
//	fetch_budget.go     //go:build faults     开关关着时走正确的实现，开着时走有缺陷的那个
//
// # 不露痕迹
//
// 盲测时人和诊断 Agent 都会看 pprof 的调用栈、日志、指标。所以（评审时逐条查）：
//
//   - 有缺陷的函数、文件、变量的名字里不出现 fault、chaos、bug、leak 这类词，起一个业务上说得通的名字；
//     带标签的那个文件按它里面的代码在做什么起名（上面的 fetch_budget.go），不用统一的后缀：文件名在 pprof 的
//     调用栈里，每个故障点都叫 x_variant.go 的话，见过一次就认得出。对本包的调用只有包级变量的那一行和一次 On()，On 不在缺陷发生的调用栈上。
//   - 有缺陷的路径不打多余的日志、不加指标。开关被打开这件事本包也不打日志、不记指标，由注入脚本记在答案文件里。
//   - 开关的名字是不透明的编号（f01 到 f99），和场景的对应关系只在答案文件里。
//   - 缺陷要有触发条件，像真的那样（“下游超时的时候才泄漏”），不是开关一开就每秒泄漏一百个。
//   - 不进资金、库存扣减、订单状态机的路径；要写坏数据只能是派生数据，并且只在 oppenheimer-e2e 里做。
//
// # 自动关
//
// 打开时必须有 ttl，到了进程自己关：开发机断网、注入脚本死掉，故障也不会留在集群上。
// 泄漏类的故障关了开关之后已经泄漏的不会回来，恢复要重启 Pod。
//
// 重启后还要在的故障（panic 导致反复重启）用环境变量 FAULT_FILE 指的文件：进程启动时读一次，
// 里面列出的开关一登记就是开着的，没有 ttl。文件不存在不算错。
package fault

// FileEnv 是放“启动时就打开哪些开关”的文件路径的环境变量。只有带 faults 标签的构建会读。
const FileEnv = "FAULT_FILE"
